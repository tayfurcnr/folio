const tr: Record<string, string> = Object.fromEntries(Object.entries(en).map(([source, translated]) => [translated, source]))

export function getInitialEditorLocale(): EditorLocale {
  if (typeof window === 'undefined') return 'tr'
  const stored = window.localStorage.getItem(STORAGE_KEY)
  if (stored === 'tr' || stored === 'en') return stored
  return window.navigator.language.toLowerCase().startsWith('en') ? 'en' : 'tr'
}

export function getEditorLocale(): EditorLocale {
  if (typeof document === 'undefined') return 'tr'
  return document.documentElement.lang.toLowerCase().startsWith('en') ? 'en' : 'tr'
}

const LocaleContext = createContext<LocaleContextValue | null>(null)

export function LocaleProvider({ children }: { readonly children: ReactNode }) {
  const [locale, setLocaleState] = useState<EditorLocale>(getInitialEditorLocale)
  const setLocale = (next: EditorLocale) => {
    setLocaleState(next)
    window.localStorage.setItem(STORAGE_KEY, next)
  }
  useEffect(() => { document.documentElement.lang = locale }, [locale])
  const value = useMemo<LocaleContextValue>(() => ({ locale, setLocale, t: (source) => locale === 'en' ? (en[source] ?? source) : (tr[source] ?? source) }), [locale])
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale(): LocaleContextValue {
  const value = useContext(LocaleContext)
  if (!value) throw new Error('useLocale must be used within LocaleProvider')
  return value
}
